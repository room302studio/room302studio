"""Cut a few marks out of EJ's hand-drawn sprite (website2 assets/hand-drawn/master.svg)
into a small JS module for room302: { name: { viewBox, paths: [{d, stroke}] } }.
Keeps only paths whose bounding box sits inside the mark's manifest crop.
Run: uv run --with svgelements python3 scripts/extract-hand-drawn.py"""
import json, os, re
from svgelements import SVG, Path

SRC = os.path.expanduser("~/code/website2/assets/hand-drawn")
NAMES = ["arrow-right-long", "arrow-down-curve", "arrow-bend-down-right", "circle-md", "circle-lg",
         "star-4pt", "scribble", "circled-1", "circled-2", "circled-3", "circled-4", "mark-dash"]
man = {a["name"]: a for a in json.load(open(f"{SRC}/manifest.json"))}
raw = open(f"{SRC}/master.svg").read()
# class -> stroked? (st0 is a 2px stroke; st1/st2 are fills)
svg = SVG.parse(f"{SRC}/master.svg", reify=True)
out = {}
for n in NAMES:
    a = man[n]; x0, y0, x1, y1 = a["x"], a["y"], a["x"] + a["w"], a["y"] + a["h"]
    paths = []
    for el in svg.elements():
        if not isinstance(el, Path) or not len(el):
            continue
        bx = el.bbox()
        if not bx:
            continue
        cx, cy = (bx[0] + bx[2]) / 2, (bx[1] + bx[3]) / 2
        if x0 - 2 <= bx[0] and bx[2] <= x1 + 2 and y0 - 2 <= bx[1] and bx[3] <= y1 + 2:
            stroked = el.values.get("class") == "st0"
            paths.append({"d": el.d(), "stroke": stroked})
    out[n] = {"viewBox": f"{x0} {y0} {a['w']} {a['h']}", "paths": paths}
    print(n, len(paths), "paths")
js = "// Generated by scripts/extract-hand-drawn.py from EJ's scanned notebook marks.\n// Do not edit by hand; re-run the script.\nexport default " + json.dumps(out, separators=(",", ":")) + "\n"
os.makedirs("utils", exist_ok=True)
open("utils/handDrawnMarks.js", "w").write(js)
print("bytes:", len(js))
